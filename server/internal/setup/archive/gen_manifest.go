//go:build ignore

// gen_manifest writes manifest_gen.go, build 1.0.903.854's file list (path, size, SHA-256) from the repository's
// docs/file_manifest.csv (columns path, size_A, sha256_A; rows without size_A belong to build 754 only). go:embed can't
// reach docs/, so the table is generated into the package; TestManifestMatchesDocs fails when the two disagree.
//
// Run from server/internal/setup/archive:
//
//	go generate        (or: go run gen_manifest.go)
package main

import (
	"bytes"
	"encoding/csv"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strconv"
)

func main() {
	csvPath := filepath.Join("..", "..", "..", "..", "docs", "file_manifest.csv")
	f, err := os.Open(csvPath)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	rows, err := csv.NewReader(f).ReadAll()
	if err != nil {
		log.Fatalf("%s: %v", csvPath, err)
	}
	col := map[string]int{}
	for i, name := range rows[0] {
		col[name] = i
	}
	type entry struct {
		path, sha string
		size      int64
	}
	var files []entry
	for _, r := range rows[1:] {
		if r[col["size_A"]] == "" {
			continue
		}
		size, err := strconv.ParseInt(r[col["size_A"]], 10, 64)
		if err != nil {
			log.Fatalf("%s: %v", r[col["path"]], err)
		}
		files = append(files, entry{r[col["path"]], r[col["sha256_A"]], size})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].path < files[j].path })
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_manifest.go from docs/file_manifest.csv; DO NOT EDIT.\n\n")
	b.WriteString("package archive\n\n")
	b.WriteString("// build854 is docs/file_manifest.csv's build-854 side (Dawngate.zip's files), sorted by path.\n")
	b.WriteString("var build854 = []File{\n")
	for _, x := range files {
		fmt.Fprintf(&b, "\t{%q, %d, %q},\n", x.path, x.size, x.sha)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("manifest_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote manifest_gen.go: %d files\n", len(files))
}
